/**
 * 사용자 입력 데이터를 받아 프롬프트 전문을 완성합니다.
 * @param {Object} data 
 * @returns {string} 완성된 프롬프트
 */
function buildFullPrompt(data) {
  const company = (data.company || '').trim() || '[기업명 미입력]';
  const job = (data.job || '').trim() || '[직무 미입력]';
  const org = (data.org || '').trim() || '해당 없음 (조직 미지정)';
  const jobUrl = (data.jobUrl || '').trim() || '제공되지 않음 (공식 채용페이지, 사업보고서 등 최신 1차 자료 탐색 요망)';
  
  // 채용공고 내용 조합 (업무내용, 지원자격, 우대사항)
  const jobDesc = (data.jobDesc || '').trim();
  const qualifications = (data.qualifications || '').trim();
  const preferred = (data.preferred || '').trim();
  
  let jobContent = '';
  if (jobDesc || qualifications || preferred) {
    const parts = [];
    if (jobDesc) parts.push(`[업무내용]\n${jobDesc}`);
    if (qualifications) parts.push(`[지원자격]\n${qualifications}`);
    if (preferred) parts.push(`[우대사항]\n${preferred}`);
    jobContent = parts.join('\n\n');
  } else {
    jobContent = '공고 내용 직접 입력 없음 (해당 기업 최신 공식 채용공고 탐색 요망)';
  }

  const grade = data.grade || '4학년';
  const major = (data.major || '').trim() || '기계공학과';
  
  // 내 경험 처리
  let experience = (data.experience || '').trim();
  if (!experience) {
    if (grade === '1학년' || grade === '2학년') {
      experience = `${grade}으로 아직 직무 관련 경험이 부족하므로, 이 채용공고를 바탕으로 앞으로 대학 생활 동안 무엇을 준비해야 할지 로드맵과 활동 추천을 적어줘.`;
    } else {
      experience = `직접 입력한 경험 없음 (해당 직무 합격을 위해 ${major} 전공자가 어필하기 가장 유리한 일반적인 캡스톤/프로젝트/실습 활동 예시를 바탕으로 분석해줘.)`;
    }
  }

  const essayQuestions = (data.essayQuestions || '').trim() || '[자소서 문항 미입력]';

  // 새로 정돈된 상단 헤더
  const header = `너는 현재 대기업 채용 컨설턴트 + 현직자 직무분석가 + 산업분석 애널리스트 역할을 맡는다.

내가 지원하고자 하는 기업과 직무에 대해 단순히 채용공고를 요약하는 수준이 아니라,

"이 회사에서 이 직무를 맡으면 실제로 무슨 일을 하는지 / 회사가 왜 이 직무를 채용하는지 / 어떤 역량을 가진 지원자를 원하는지 / 어떤 방식으로 일하는 사람을 선호하는지 / 내 경험 중 무엇을 활용해야 하는지 / 내가 무엇을 준비해야 하는지"

까지 이해할 수 있도록 매우 구체적으로 분석해줘.

---

# 분석 대상

기업명: ${company}
지원직무: ${job}
사업부/조직: ${org}
채용공고 링크: ${jobUrl}

채용공고 내용:
${jobContent}

학년: ${grade}
전공: ${major}

내 경험:
${experience}

자소서 문항:
${essayQuestions}

---
`;

  return header + PROMPT_BODY;
}

/**
 * 프롬프트 내에 '(입력)' 토큰이 남아있는지 검사합니다.
 * @param {string} promptText 
 * @returns {number} 남아있는 (입력) 개수
 */
function countRemainingPlaceholders(promptText) {
  const matches = promptText.match(/\(입력\)/g);
  return matches ? matches.length : 0;
}