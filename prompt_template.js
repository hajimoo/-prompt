/**
 * Role 텍스트에서 소제목(■ ...)만 뽑아냅니다. 소제목이 없으면 null.
 */
function extractRoleHeadings(roleText) {
  const heads = (roleText || '').split('\n')
    .map(l => l.trim())
    .filter(l => /^■/.test(l))
    .map(l => l.replace(/^■\s*/, ''));
  return heads.length ? heads : null;
}

/**
 * 학년에 따라 직무기술서 발췌 내용을 다르게 조립합니다.
 * - 1·2학년: 직무 이해(요약·업무 영역) + 공식 추천과목 + 지원자격(=졸업 목표) + 우대사항(=스펙 타깃) + Career Vision
 * - 3·4학년: 배포 사이트와 동일한 형식 그대로 ([업무내용] / [지원자격] / [우대사항])
 */
function buildJobContent(data, isJunior, major) {
  const t = v => (v || '').trim();
  const summary = t(data.summary);
  const jobDesc = t(data.jobDesc);
  const qualifications = t(data.qualifications);
  const preferred = t(data.preferred);
  const subjects = t(data.subjects);
  const careerVision = t(data.careerVision);

  if (!isJunior && !jobDesc && !qualifications && !preferred) {
    return '공고 내용 직접 입력 없음 (해당 기업 최신 공식 채용공고 탐색 요망)';
  }
  if (!summary && !jobDesc && !qualifications && !preferred && !subjects && !careerVision) {
    return isJunior
      ? '공고 내용 직접 입력 없음 (해당 기업 최신 공식 채용공고/직무기술서 탐색 요망)'
      : '공고 내용 직접 입력 없음 (해당 기업 최신 공식 채용공고 탐색 요망)';
  }

  const parts = [];
  if (isJunior) {
    if (summary) parts.push(`[직무 요약]\n${summary}`);
    if (jobDesc) {
      const heads = extractRoleHeadings(jobDesc);
      parts.push(heads
        ? `[핵심 업무 영역 (직무기술서 Role 소제목)]\n${heads.map(h => `- ${h}`).join('\n')}\n\n[세부 업무 원문 (참고용)]\n${jobDesc}`
        : `[담당업무 / Role]\n${jobDesc}`);
    }
    parts.push(subjects
      ? `[내 전공(${major}) 공식 추천과목 = 1·2학년 수강 로드맵의 1차 근거]\n${subjects}`
      : `[내 전공(${major}) 공식 추천과목]\n직무기술서에 전공별 추천과목 없음 (업무 내용으로 역산하여 [합리적 추정] 표시)`);
    if (qualifications) parts.push(`[졸업 시점 도달 목표 = 지원자격 / Requirements]\n${qualifications}`);
    if (preferred) parts.push(`[스펙 빌드업 타깃 = 우대사항 / Pluses]\n${preferred}`);
    if (careerVision) parts.push(`[회사가 제시한 Career Vision]\n${careerVision}`);
  } else {
    // 3·4학년: 배포 중인 사이트(hajimoo.github.io/-prompt)와 동일한 형식 — [업무내용] / [지원자격] / [우대사항]
    if (jobDesc) parts.push(`[업무내용]\n${jobDesc}`);
    if (qualifications) parts.push(`[지원자격]\n${qualifications}`);
    if (preferred) parts.push(`[우대사항]\n${preferred}`);
    if (!parts.length) return '공고 내용 직접 입력 없음 (해당 기업 최신 공식 채용공고 탐색 요망)';
  }
  return parts.join('\n\n');
}

